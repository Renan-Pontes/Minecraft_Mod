def rename(key, text, pairs):
    if not key.startswith(P) or not key[len(P):].startswith(RENAME_GROUPS):
        return text
    for a, b in pairs:
        text = text.replace(a, b)
    return text


def merge(fname, idx):
    path = os.path.join(LANG, fname)
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    for k, v in T.items():
        data[P + k] = v[idx]
    for k, v in RAW.items():
        data[k] = v[idx]
    data = {k: rename(k, v, RENAME_PT if idx == 0 else RENAME_EN) for k, v in data.items()}
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(dict(sorted(data.items())), f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("%s: %d chaves v1.4" % (fname, len(T)))


